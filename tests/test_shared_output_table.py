_STRUCT_FIELDS = ("tm_year", "tm_mon", "tm_mday", "tm_hour", "tm_min", "tm_sec",
                  "tm_wday", "tm_yday", "tm_isdst", "tm_zone", "tm_gmtoff")
_STRUCT_PARTS = (2024, 1, 2, 3, 4, 5, 1, 2, -1)


@pytest.mark.parametrize("many", [False, True])
def test_struct_time_table_retains_its_scalar_root_and_all_json_fields(many: bool) -> None:
    value = struct_time(_STRUCT_PARTS)
    assert _sqlaero._escape_projection(value, many=many) == "'2024-01-02 03:04:05'"
    assert json_dumps(value) == (b'{"tm_year":2024,"tm_mon":1,"tm_mday":2,"tm_hour":3,'
                                b'"tm_min":4,"tm_sec":5,"tm_wday":1,"tm_yday":2,'
                                b'"tm_isdst":-1,"tm_zone":null,"tm_gmtoff":null}')


@pytest.mark.parametrize("index", range(6))
@pytest.mark.parametrize(("replacement", "error"), [(-1, ValueError), (1.5, TypeError)])
def test_struct_time_table_field_policy_is_target_specific(index: int, replacement, error) -> None:
    parts = list(_STRUCT_PARTS)
    parts[index] = replacement
    value = struct_time(parts)
    with pytest.raises(error):
        _sqlaero._escape_projection(value)
    assert json.loads(json_dumps(value)) == dict(zip(_STRUCT_FIELDS, (*parts, None, None)))


def test_struct_time_table_index_protocol_is_not_a_json_object_conversion() -> None:
    class Year:
        def __index__(self) -> int:
            return 2024
    value = struct_time((Year(), *_STRUCT_PARTS[1:]))
    assert _sqlaero._escape_projection(value) == "'2024-01-02 03:04:05'"
    with pytest.raises(TypeError):
        json_dumps(value)


def test_struct_time_table_keeps_numpy_integer_values() -> None:
    np = pytest.importorskip("numpy")
    value = struct_time((np.int64(2024), *_STRUCT_PARTS[1:]))
    assert _sqlaero._escape_projection(value) == "'2024-01-02 03:04:05'"
    assert json.loads(json_dumps(value))["tm_year"] == 2024


def test_struct_time_table_unused_auxiliary_fields_are_not_sql_inputs() -> None:
    value = struct_time((*_STRUCT_PARTS[:6], object(), 2, -1))
    assert _sqlaero._escape_projection(value) == "'2024-01-02 03:04:05'"
    with pytest.raises(TypeError) as caught:
        json_dumps(value)
    assert "tm_wday" in "\n".join(caught.value.__notes__)
