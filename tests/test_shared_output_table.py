def test_formfeed_table_accepts_equivalent_valid_json_escape() -> None:
    # 005/11 explicitly permits \f or an equivalent Unicode escape.
    assert _sqlaero._escape_projection("a\fb") == "'a\fb'"
    actual = json_dumps("a\fb")
    assert type(actual) is bytes and json.loads(actual) == "a\fb"
    assert b"\x0c" not in actual


def test_index_protocol_alone_is_not_an_integer_source() -> None:
    # 003/08 is deliberately distinct from struct_time's field protocol.
    class OnlyIndex:
        def __index__(self):
            raise AssertionError("unsupported objects must not be coerced")
    source = OnlyIndex()
    for convert in (_sqlaero._escape_projection, json_dumps):
        with pytest.raises(TypeError):
            convert(source)


def test_boolean_table_value_and_key_have_distinct_roles() -> None:
    assert _sqlaero._escape_projection({"flag": True}) == ("1",)
    assert json_dumps({"flag": True}) == b'{"flag":true}'
    assert _sqlaero._escape_projection({True: "ab"}) == ("'ab'",)
    with pytest.raises(TypeError):
        json_dumps({True: "ab"})


def test_text_json_does_not_inherit_a_mysql_codec_failure() -> None:
    with pytest.raises(UnicodeEncodeError):
        _sqlaero._escape_projection("中文", charset="latin1")
    assert json_dumps("中文") == '"中文"'.encode("utf-8")


def test_no_backslash_mode_changes_only_the_mysql_target() -> None:
    assert _sqlaero._escape_projection("O'Reilly", no_backslash=True) == "'O''Reilly'"
    assert json_dumps("O'Reilly") == b'"O\'Reilly"'


def test_canonically_similar_source_text_is_not_normalized() -> None:
    for value in ("\u00e9", "e\u0301"):
        assert _sqlaero._escape_projection(value) == "'" + value + "'"
        assert json.loads(json_dumps(value)) == value
    assert json_dumps({"\u00e9": 7, "e\u0301": 8}) == '{"é":7,"é":8}'.encode("utf-8")


